-- ============================================================================
-- Baseline schema — equivalent of the schema TypeORM `synchronize` produced from
-- the NestJS entities, PLUS the hand-applied stored procedures / triggers from
-- sql/kanban_tasks.sql that the services depend on (fn_set_ticket_id trigger,
-- fn_move_task, fn_reorder_task, fn_reorder_subtask).
--
-- Every statement is idempotent so this can also be applied to a database that
-- was already created by the Nest app (or use flyway baseline-on-migrate).
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ---------------------------------------------------------------------------
-- Enum types (TypeORM default names: <table>_<column>_enum, unless enumName set)
-- ---------------------------------------------------------------------------
DO $$ BEGIN
  CREATE TYPE users_role_enum AS ENUM (
    'backend_developer','frontend_developer','fullstack_developer','qa','devops',
    'designer','product_manager','tech_lead');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE tasks_status_enum AS ENUM ('open','in_progress','in_review','done','cancelled');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE tasks_priority_enum AS ENUM ('no_priority','urgent','high','medium','low');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE notifications_type_enum AS ENUM ('comment_created','comment_mentioned','task_assigned','task_updated');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE project_role AS ENUM ('owner','admin','member','viewer');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
ALTER TYPE project_role ADD VALUE IF NOT EXISTS 'viewer';

DO $$ BEGIN
  CREATE TYPE task_subscription_source AS ENUM ('assigned','mentioned','commented','manual','created');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE task_activity_action AS ENUM (
    'task_created','task_title_updated','task_description_updated','task_status_changed',
    'task_priority_changed','task_due_date_changed','task_assignee_added','task_assignee_removed',
    'task_label_added','task_label_removed','task_moved','task_reordered');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  email         VARCHAR(255) NOT NULL,
  full_name     VARCHAR(150) NOT NULL,
  password_hash TEXT NOT NULL,
  role          users_role_enum NOT NULL DEFAULT 'backend_developer',
  avatar_url    TEXT NOT NULL DEFAULT 'https://api.dicebear.com/9.x/initials/svg?seed=default',
  is_active     BOOLEAN NOT NULL DEFAULT true,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_users_email" UNIQUE (email)
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_is_active ON users (is_active);

-- ---------------------------------------------------------------------------
-- projects (id generated by the application: 8 alphanumeric chars)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS projects (
  id             VARCHAR(8) PRIMARY KEY,
  name           VARCHAR(100) NOT NULL,
  tag            VARCHAR(10) NOT NULL,
  ticket_counter INT NOT NULL DEFAULT 0,
  description    TEXT,
  created_by     UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_projects_name" UNIQUE (name),
  CONSTRAINT "UQ_projects_tag" UNIQUE (tag)
);

-- ---------------------------------------------------------------------------
-- project_members
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_members (
  project_id VARCHAR(8) NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id    UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role       project_role NOT NULL DEFAULT 'member',
  joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_project_members_user_id ON project_members (user_id);

-- ---------------------------------------------------------------------------
-- refresh_tokens
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS refresh_tokens (
  id          SERIAL PRIMARY KEY,
  user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL,
  device_info VARCHAR(255),
  ip_address  VARCHAR(45),
  is_revoked  BOOLEAN NOT NULL DEFAULT false,
  expires_at  TIMESTAMPTZ NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT "UQ_refresh_tokens_token_hash" UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);

-- ---------------------------------------------------------------------------
-- teams / team_members (project scoped)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS teams (
  id          SERIAL PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,
  description TEXT,
  color       VARCHAR(20),
  is_active   BOOLEAN NOT NULL DEFAULT true,
  project_id  VARCHAR(8) NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
