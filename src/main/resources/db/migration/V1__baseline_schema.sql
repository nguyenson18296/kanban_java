CREATE OR REPLACE FUNCTION fn_set_ticket_id()
RETURNS TRIGGER AS $$
DECLARE
    v_project_id VARCHAR(8);
    v_tag        VARCHAR(10);
    v_next_num   INT;
BEGIN
    SELECT kc.project_id INTO v_project_id
    FROM kanban_columns kc
    WHERE kc.id = NEW.column_id;

    IF v_project_id IS NULL THEN
        RAISE EXCEPTION 'Column % has no project', NEW.column_id;
    END IF;

    UPDATE projects
    SET ticket_counter = ticket_counter + 1
    WHERE id = v_project_id
    RETURNING ticket_counter, tag INTO v_next_num, v_tag;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Project % not found when generating ticket ID', v_project_id;
    END IF;

    IF v_tag IS NULL THEN
        RAISE EXCEPTION 'Project % has no tag assigned', v_project_id;
    END IF;

    NEW.ticket_number := v_next_num;
    NEW.ticket_id := v_tag || '-' || v_next_num;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_tasks_set_ticket_id ON tasks;
CREATE TRIGGER trg_tasks_set_ticket_id
    BEFORE INSERT ON tasks
    FOR EACH ROW
    EXECUTE FUNCTION fn_set_ticket_id();

CREATE OR REPLACE FUNCTION fn_move_task(
    p_task_id       UUID,
    p_new_column_id INT,
    p_new_position  INT
)
RETURNS VOID AS $$
DECLARE
    v_old_column_id INT;
    v_old_position  INT;
BEGIN
    SELECT column_id, position INTO v_old_column_id, v_old_position
    FROM tasks WHERE id = p_task_id;

    IF v_old_column_id IS NULL THEN
        RAISE EXCEPTION 'Task with id "%" not found', p_task_id;
    END IF;

    UPDATE tasks
    SET position = position - 1
    WHERE column_id = v_old_column_id
      AND position > v_old_position;

    UPDATE tasks
    SET position = position + 1
    WHERE column_id = p_new_column_id
      AND position >= p_new_position;

    UPDATE tasks
    SET column_id = p_new_column_id,
        position  = p_new_position
    WHERE id = p_task_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_reorder_task(
    p_task_id      UUID,
    p_new_position INT
)
RETURNS VOID AS $$
DECLARE
    v_column_id    INT;
    v_old_position INT;
BEGIN
    SELECT column_id, position INTO v_column_id, v_old_position
    FROM tasks WHERE id = p_task_id;

    IF v_column_id IS NULL THEN
        RAISE EXCEPTION 'Task with id "%" not found', p_task_id;
    END IF;

    IF v_old_position = p_new_position THEN
        RETURN;
    END IF;

    IF p_new_position < v_old_position THEN
        UPDATE tasks
        SET position = position + 1
        WHERE column_id = v_column_id
          AND position >= p_new_position
          AND position < v_old_position;
    ELSE
        UPDATE tasks
        SET position = position - 1
        WHERE column_id = v_column_id
          AND position > v_old_position
          AND position <= p_new_position;
    END IF;

    UPDATE tasks SET position = p_new_position WHERE id = p_task_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION fn_reorder_subtask(
    p_subtask_id   UUID,
    p_parent_id    UUID,
    p_new_position INT
)
RETURNS VOID AS $$
DECLARE
    v_old_position INT;
BEGIN
    SELECT position INTO v_old_position
    FROM tasks WHERE id = p_subtask_id AND parent_id = p_parent_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Subtask "%" not found under parent "%"', p_subtask_id, p_parent_id;
    END IF;

    IF v_old_position = p_new_position THEN
        RETURN;
    END IF;

    IF p_new_position < v_old_position THEN
        UPDATE tasks
        SET position = position + 1
        WHERE parent_id = p_parent_id
          AND position >= p_new_position
          AND position < v_old_position;
    ELSE
        UPDATE tasks
        SET position = position - 1
        WHERE parent_id = p_parent_id
          AND position > v_old_position
          AND position <= p_new_position;
    END IF;

    UPDATE tasks SET position = p_new_position WHERE id = p_subtask_id;
END;
$$ LANGUAGE plpgsql;
