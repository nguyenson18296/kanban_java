-- ---------------------------------------------------------------------------
-- tasks (+ join tables)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tasks (
  id            UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  title         VARCHAR(255) NOT NULL,
  description   TEXT,
  status        tasks_status_enum NOT NULL DEFAULT 'open',
